export function generateCode(view, nodes, edges, cloud, rps = 100) {
  if (view === 'k8s') return generateK8s(nodes)
  if (view === 'json') return toDesignJSON(nodes, edges, rps)
  if (view === 'mermaid') return toMermaid(nodes, edges)
  if (view === 'excalidraw') return toExcalidraw(nodes, edges)
  if (view === 'terraform') return generateTerraform(nodes, cloud)
  if (view === 'openapi') return generateOpenAPI(nodes, edges)
  return generateCompose(nodes, edges)
}

const K8S_TYPES = new Set(['app', 'micro', 'gateway', 'fastapi', 'worker', 'ws', 'llmworker', 'embed', 'agentgraph', 'guard', 'grpc'])
export function generateK8s(nodes) {
  const svcs = nodes.filter(n => K8S_TYPES.has(n.type))
  if (!svcs.length) return '# No service tiers on the canvas - add an app, service, gateway or worker first.\n'
  const out = ['# Generated by ArchSim - the resource philosophy is the k8s-resources drill:',
    '# requests = what the scheduler RESERVES; limits = where the kernel KILLS (memory) or THROTTLES (CPU).',
    '# HPA scales on requests, so honest requests are the autoscaling contract.', '']
  const name = (n) => String(n.label || n.id).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40) || n.id
  for (const n of svcs) {
    const nm = name(n); const r = Math.max(1, n.replicas || 1)
    out.push(`---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${nm}
  labels: { app: ${nm}, archsim-type: ${n.type} }
spec:
  replicas: ${r}
  selector: { matchLabels: { app: ${nm} } }
  template:
    metadata: { labels: { app: ${nm} } }
    spec:
      containers:
        - name: ${nm}
          image: registry.example.com/${nm}:latest
          ports: [{ containerPort: 8080 }]
          resources:
            requests: { cpu: 250m, memory: 256Mi }   # measure the working set, then raise - the scheduler packs on THESE
            limits: { cpu: "1", memory: 512Mi }      # memory limit is a kill line, not a suggestion
          readinessProbe: { httpGet: { path: /healthz, port: 8080 }, periodSeconds: 5 }
          livenessProbe: { httpGet: { path: /healthz, port: 8080 }, initialDelaySeconds: 10, periodSeconds: 10 }
---
apiVersion: v1
kind: Service
metadata: { name: ${nm} }
spec:
  selector: { app: ${nm} }
  ports: [{ port: 80, targetPort: 8080 }]`)
  }
  const big = svcs.reduce((a, b) => ((b.replicas || 1) > (a.replicas || 1) ? b : a))
  out.push(`---
# HPA on the widest tier - scaling math runs on REQUESTS, which is why they must be honest
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata: { name: ${name(big)} }
spec:
  scaleTargetRef: { apiVersion: apps/v1, kind: Deployment, name: ${name(big)} }
  minReplicas: ${Math.max(1, big.replicas || 1)}
  maxReplicas: ${Math.max(2, (big.replicas || 1) * 3)}
  metrics: [{ type: Resource, resource: { name: cpu, target: { type: Utilization, averageUtilization: 70 } } }]`)
  return out.join('\n') + '\n'
}
