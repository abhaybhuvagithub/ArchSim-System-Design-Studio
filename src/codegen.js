export function generateCompose(nodes, edges) {
  const runnable = nodes.filter(n => COMPOSE_IMAGES[n.type])
  const skipped = nodes.filter(n => !COMPOSE_IMAGES[n.type] && !CATALOG[n.type]?.source)
  const deps = {}
  for (const e of edges) (deps[e.from] ||= []).push(e.to)
  const nameOf = Object.fromEntries(nodes.map(n => [n.id, slug(n.label)]))

  const HEALTH = {
    sql: 'pg_isready -U postgres', cache: 'redis-cli ping', nosql: 'mongosh --quiet --eval "db.runCommand({ping:1})"',
    queue: 'rabbitmq-diagnostics -q ping', mq: 'rabbitmq-diagnostics -q ping',
  }
  const L = ['# Generated by ArchSim from the live canvas — edit the diagram, not this file.',
    '# Apply an Improve suggestion or a chaos Quick Fix and regenerate: the code follows the design.',
    'services:']
  for (const n of runnable) {
    const c = COMPOSE_IMAGES[n.type]
    L.push(`  ${nameOf[n.id]}:`)
    L.push(`    image: ${c.image}`)
    L.push(`    restart: unless-stopped`)
    if (c.command) L.push(`    command: ${c.command}`)
    if ((n.replicas || 1) > 1) {
      L.push(`    deploy:`)
      L.push(`      replicas: ${n.replicas}   # from the canvas — the Capacity tab sized this tier`)
    }
    if (c.ports && (n.replicas || 1) === 1) L.push(`    ports: [${c.ports.map(p => `"${p}"`).join(', ')}]`)
    if (c.env) { L.push('    environment:'); for (const [k, v] of Object.entries(c.env)) L.push(`      ${k}: ${v}`) }
    if (HEALTH[n.type]) {
      L.push(`    healthcheck:`)
      L.push(`      test: ["CMD-SHELL", "${HEALTH[n.type]}"]`)
      L.push(`      interval: 5s`)
      L.push(`      retries: 10`)
    }
    const dependsOn = (deps[n.id] || []).map(id => nameOf[id]).filter(m => runnable.some(r => nameOf[r.id] === m))
    if (dependsOn.length) L.push(`    depends_on: [${[...new Set(dependsOn)].join(', ')}]`)
  }
  if (skipped.length) {
    L.push('')
    L.push('# Not containers — these map to managed services (see the Terraform tab):')
    for (const n of skipped) L.push(`#   ${n.label} (${CATALOG[n.type]?.name || n.type})`)
  }
  return L.join('\n') + '\n'
}

// A Terraform skeleton naming the real managed service for each component on
// the selected cloud. Resource bodies are deliberately minimal — this is the
// shape of the deployment, not a copy-paste production stack.
const TF_PROVIDERS = {
  aws: { source: 'hashicorp/aws', block: 'provider "aws" {\n  region = var.region\n}' },
  gcp: { source: 'hashicorp/google', block: 'provider "google" {\n  project = var.project\n  region  = var.region\n}' },
  azure: { source: 'hashicorp/azurerm', block: 'provider "azurerm" {\n  features {}\n}' },
  oci: { source: 'oracle/oci', block: 'provider "oci" {\n  region = var.region\n}' },
}

export function generateTerraform(nodes, cloud) {
  const p = TF_PROVIDERS[cloud]
  if (!p) {
    return '# Pick a specific cloud (AWS, GCP, Azure or OCI) in the toolbar to generate\n# Terraform — "Generic" has no provider to target.\n'
  }
  const L = ['# Generated by ArchSim from the live canvas for ' + cloud.toUpperCase() + '.',
    '# Skeleton, not a production stack: names and counts are real, bodies are minimal.',
    '',
    'terraform {',
    '  required_providers {',
    `    ${cloud === 'gcp' ? 'google' : cloud === 'azure' ? 'azurerm' : cloud} = { source = "${p.source}" }`,
    '  }',
    '}',
    '',
    p.block,
    '']
  for (const n of nodes) {
    if (CATALOG[n.type]?.source) continue
    const svc = serviceName(n.type, cloud)
    const name = slug(n.label).replace(/-/g, '_')
    L.push(`# ${n.label} → ${svc || 'no mapped service'}${(n.replicas || 1) > 1 ? ` × ${n.replicas}` : ''}`)
    if (!svc || svc === 'no public equivalent' || svc === 'no equivalent') {
      L.push(`# (no ${cloud.toUpperCase()} equivalent — self-host or substitute)`)
      L.push('')
      continue
    }
    L.push(`module "${name}" {`)
    L.push(`  source   = "./modules/${slug(n.type)}"`)
    L.push(`  name     = "${slug(n.label)}"`)
    L.push(`  service  = "${svc}"`)
    if ((n.replicas || 1) > 1) L.push(`  replicas = ${n.replicas}`)
    L.push('}')
    L.push('')
  }
  return L.join('\n')
}

// One OpenAPI document covering the service tiers: each service node becomes
// a tagged path group, each downstream store it talks to becomes a resource.
const SERVICE_TYPES = new Set(['web', 'app', 'micro', 'grpc', 'bff', 'ws', 'gateway'])
const STORE_TYPES = new Set(['sql', 'nosql', 'cache', 'search', 'vector', 'blob'])

export function generateOpenAPI(nodes, edges) {
  const services = nodes.filter(n => SERVICE_TYPES.has(n.type))
  if (!services.length) {
    return '# Add a service tier (Web, App, Microservice, Gateway...) to the canvas\n# and its API contract will appear here.\n'
  }
  const byId = Object.fromEntries(nodes.map(n => [n.id, n]))
  const L = ['openapi: 3.0.3',
    'info:',
    '  title: Generated from the ArchSim canvas',
    '  description: One path group per service tier; resources inferred from the stores each service talks to.',
    '  version: 1.0.0',
    'paths:']
  for (const s of services) {
    const stores = edges.filter(e => e.from === s.id && STORE_TYPES.has(byId[e.to]?.type)).map(e => byId[e.to])
    const resources = stores.length ? stores : [{ label: 'items' }]
    for (const st of resources) {
      const r = slug(st.label)
      L.push(`  /${slug(s.label)}/${r}:`)
      L.push('    get:')
      L.push(`      tags: ["${s.label}"]`)
      L.push(`      summary: List ${r} (backed by ${st.type ? CATALOG[st.type]?.name || st.type : 'the service'})`)
      L.push('      responses: { "200": { description: OK } }')
      L.push('    post:')
      L.push(`      tags: ["${s.label}"]`)
      L.push(`      summary: Create in ${r}`)
      L.push('      responses: { "201": { description: Created } }')
    }
  }
  return L.join('\n') + '\n'
}

